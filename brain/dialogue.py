MOODS = tuple(MOOD_OPENERS)
ACTIVITIES = tuple(
    activity
    for activity in ACTIVITY_OBSERVATIONS
    if activity not in {"spotify_browsing", "ai_chat"}
)


def compose_candidates(
    activity: str,
    values: dict[str, Any],
    mood: str,
) -> list[str]:
    """Return all complete opener/observation/closer combinations."""
    return [
        f"{opener} {observation} {closer}"
        for opener, observation, closer in compose_candidate_parts(activity, values, mood)
    ]


def compose_candidate_parts(
    activity: str,
    values: dict[str, Any],
    mood: str,
    excluded_openers: Iterable[str] = (),
    excluded_closers: Iterable[str] = (),
) -> list[tuple[str, str, str]]:
    """Return rendered clauses while allowing recent openers and closers to be avoided."""
    activity = activity if activity in ACTIVITY_OBSERVATIONS else "user_chat"
    mood = mood if mood in MOOD_OPENERS else "bored"
    observations = ACTIVITY_OBSERVATIONS[activity]
    blocked_openers = set(excluded_openers)
    blocked_closers = set(excluded_closers)
    openers = [phrase for phrase in MOOD_OPENERS[mood] if phrase not in blocked_openers]
    closers = [phrase for phrase in MOOD_CLOSERS[mood] if phrase not in blocked_closers]
    openers = openers or list(MOOD_OPENERS[mood])
    closers = closers or list(MOOD_CLOSERS[mood])
    candidates: list[tuple[str, str, str]] = []
    for opener, observation, closer in product(openers, observations, closers):
        rendered_observation = observation.format(
            title=values.get("title") or "the current activity",
            artist=values.get("artist") or "an artist",
            app=values.get("app") or "the foreground app",
            ram_gb=values.get("ram_gb") or "an unknown amount",
            unread_count=values.get("unread_count", 0),
        )
        candidates.append((opener, rendered_observation, closer))
    return candidates
